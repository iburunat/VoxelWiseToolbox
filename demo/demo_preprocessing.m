%% DEMO_PREPROCESSING  The temporal preprocessing chain, in order
%
% Simulates one participant and applies each temporal preprocessing step in
% sequence. The task regressor is detrended, filtered, and smoothed to match
% the processed data before the correlation map is computed and saved.
%
% Steps:
%   1. Simulate data                     fmri_simdata / fmri_simget
%   2. Detrend (remove scanner drift)    fmri_detrend
%   3. Regress motion parameters         fmri_correctmovement
%   4. Band-pass filter                  fmri_bandpassfilter
%   5. Apply temporal smoothing          fmri_tempsmooth
%   6. Apply voxelwise z-scoring         fmri_zscorevoldata
%   7. Process the regressor, correlate, save and display
%
% Signal quality is reported alongside the chain with fmri_snrt and fmri_cnr.
%
% Two files are written to the current folder: demo_motion_params.txt and
% demo_data.mat.
%
% This demo and demo_glm are independent and can be run in either order.
% demo_glm simulates its own 20-participant dataset and does not load this
% demo's output.
%
% See also: demo_tempsmooth, demo_naturalistic, demo_glm

clear;
close all;
if exist('fmritoolbox_setup', 'file')
    fmritoolbox_setup;
else
    error('Please run fmritoolbox_setup.m from the toolbox root directory first.');
end
fprintf('=== VoxelWise Toolbox preprocessing demo ===\n\n');

%% 1. Simulate one participant
% -------------------------------------------------------------------
TR         = 2;      % repetition time (seconds)
n_scans    = 200;    % time points
n_sources  = 10;     % activation blobs
n_network  = 3;      % first 3 blobs share time course 1 (a "network")
rng(42);
outdir = pwd;

fprintf('Step 1: Simulating data with fmri_simdata...\n');
% Full 4D volumes and simulation ground truth are not needed for this demo.
% fmri_simget reconstructs the participant from the compressed representation.
[X_comp, ~, W, svd_info] = fmri_simdata(n_sources, 1, n_scans, TR, ...
                                        [], [], [], n_network, 0, false);

data     = fmri_simget(X_comp, svd_info, 1);   % n_voxels x n_scans
n_voxels = size(data, 1);

% Use the BOLD time course generated by the simulator as the task regressor.
% This avoids introducing regressor construction into this demo, which is
% focused on preprocessing. In a real analysis, the BOLD regressor
% would be constructed from the stimulus feature and an HRF, as demonstrated
% in demo_naturalistic step 2.
bold_regressor = W.bold(:, 1, 1);

fprintf('  Data: %d voxels x %d scans (TR = %.1f s)\n\n', n_voxels, n_scans, TR);

% Example motion parameters (3 translation + 3 rotation), autocorrelated.
%
% Create example motion parameters: three translations and three rotations.
% This demonstrates how fmri_correctmovement reads a standard six-column
% SPM/FSL motion file. The data do not contain matching motion artefacts, so
% this step demonstrates function usage rather than motion recovery. Any
% motion variance removed here therefore reflects incidental overlap between
% the simulated data and the example motion parameters.
motion_params = cumsum(0.05 * randn(n_scans, 6));
motion_file   = fullfile(outdir, 'demo_motion_params.txt');
save(motion_file, 'motion_params', '-ascii');
fprintf('  Motion parameters written to: %s\n\n', motion_file);

%% 2-6. The chain
% -------------------------------------------------------------------
% fmri_bandpassfilter expects sampling frequency in Hz, not TR in seconds.
% With TR = 2 s, the correct sampling frequency is 1/TR = 0.5 Hz.
%
% fmri_tempsmooth expects sigma in seconds. Pass TR explicitly so that the
% function can convert sigma to scans.
fs = 1 / TR;                            % 0.5 Hz at TR = 2 s

% Temporal SNR is measured before the chain and again after smoothing, NOT
% after the whole chain: fmri_zscorevoldata gives every voxel zero mean and
% unit variance, so tSNR = mean/std is identically zero afterwards and would
% report nothing about the data. tCNR divides a temporal change by a temporal
% standard deviation, so the mean cancels and z-scoring leaves it unchanged;
% it is therefore read at the end. Both return a value per voxel; the median
% over voxels summarises the map, and non-finite voxels (zero temporal
% variance) are dropped rather than being counted as zero.
fprintf('Steps 2-6: detrend, motion, band-pass, smooth, z-score...\n');
s = fmri_snrt(data);   tsnr_before = median(s(isfinite(s)));

data = fmri_detrend(data);                        % 2. remove linear drift
data = fmri_correctmovement(data, motion_file);   % 3. regress motion parameters
data = fmri_bandpassfilter(data, fs, 0.01, 0.1);  % 4. retain 0.01-0.10 Hz
data = fmri_tempsmooth(data, 3, TR);              % 5. Gaussian sigma = 3 s

s = fmri_snrt(data);   tsnr_after  = median(s(isfinite(s)));

data = fmri_zscorevoldata(data);                  % 6. z-score each voxel
c    = fmri_cnr(data);

fprintf('  Done. Median tSNR %.1f before the chain, %.1f after smoothing.\n', ...
        tsnr_before, tsnr_after);
fprintf('  Median tCNR %.2f (fmri_cnr is unchanged by the z-scoring).\n\n', ...
        median(c(isfinite(c))));

%% 7. Process the regressor to match, correlate, save and display
% -------------------------------------------------------------------
% Apply the corresponding temporal operations to the regressor before
% correlating it with the processed data. Otherwise, the regressor retains
% frequencies that have already been removed from the data, which can weaken
% the correlation.
%
% Detrend, band-pass filter and smooth the regressor to match the temporal
% processing applied to the data. The regressor is not residualized against
% the example motion parameters.
%
% A 1 x T input is ambiguous: it could represent one voxel over time or one
% time point across voxels. Here it is one regressor over time. Temporarily
% suppress the orientation warning and restore it afterward.
warn_state = warning('off', 'fmri:ambiguousOrientation');
reg_proc = fmri_detrend(bold_regressor(:)');
reg_proc = fmri_bandpassfilter(reg_proc, fs, 0.01, 0.1);
reg_proc = fmri_tempsmooth(reg_proc, 3, TR);
reg_proc = reg_proc(:);
warning(warn_state);

r_map = fmri_corregressor(reg_proc, data);

demo_data_file = fullfile(outdir, 'demo_data.mat');
save(demo_data_file, 'data', 'bold_regressor', 'reg_proc', 'r_map', ...
     'TR', 'n_scans', 'n_voxels');
fprintf('Step 7: Saved %s\n', demo_data_file);
fprintf('  Contains the preprocessed data, both regressors and the r-map.\n\n');

% The threshold below is used only to make the map easier to read. It is not a
% statistical significance threshold.
display_threshold = 0.3;

figure('Name', 'Preprocessing: correlation map');
fmri_showslices(r_map, 1, 2, [-0.8 0.8], [], [], 1, [], display_threshold);
title(sprintf('Correlation with filtered regressor (display |r| >= %.1f)', ...
      display_threshold), 'FontSize', 12);

fprintf('=== Preprocessing demo complete ===\n');
fprintf('Preprocessed data and correlation map saved to:\n  %s\n', ...
        demo_data_file);
