% DEMO_NATURALISTIC  Voxelwise analysis of a continuous stimulus
%
% Simulates a small fMRI cohort and runs a complete naturalistic correlation
% analysis. Participants are presented with a continuous stimulus (a film, a
% music excerpt, a spoken narrative); a feature time series extracted from that
% stimulus is correlated with the BOLD signal at every voxel, and the
% participant-level maps are tested at the group level.
%
% Pipeline steps:
%   1. Simulate the cohort            fmri_simdata, fmri_simget
%   2. Build the BOLD regressor       fmri_doublegamma
%   3. Preprocess and correlate       fmri_detrend, fmri_correctmovement,
%                                     fmri_zscorevoldata, fmri_corregressor
%   4. Group inference                fmri_ttest, fmri_p2t
%   5. Regions and visualisation      fmri_cleanclusters, fmri_regiontable,
%                                     fmri_showslices, fmri_show3d
%
% The simulated network contains both positive and negative responses to the
% stimulus feature. Their signs are stored in sim.design.network.sign. The
% two-tailed analysis keeps the two response directions separate.
%
% All data are generated by the demo; no scanner data are required.
%
% See also: demo_preprocessing, demo_xcorr, demo_tfce, demo_csizeestimation

clear; close all;
fmritoolbox_setup;
fprintf('=== VoxelWise Toolbox: naturalistic pipeline demo ===\n\n');

%% --- Parameters -----------------------------------------------------------
TR        = 2;      % repetition time (seconds)
T         = 200;    % volumes
n_subj    = 8;      % participants
n_sources = 10;     % spatial sources
n_network = 3;      % blobs sharing time course 1, with simulator-assigned signs
phase_str = 0.8;    % inter-participant variability (see fmri_simdata)
alpha_th  = 0.001;  % voxel-level threshold, two-tailed
rng(1);

%% --- Step 1: simulate the cohort ------------------------------------------
fprintf('Step 1: Simulating %d participants, %d sources...\n', n_subj, n_sources);

% WANT_FULL = false (argument 10) suppresses assembly of the full 4D volumes;
% fmri_simget reconstructs one participant at a time in step 3.
[X_comp, ~, W, svd_info, ~, sim] = fmri_simdata(n_sources, n_subj, T, TR, ...
                                   [], [], phase_str, n_network, 1, false);

n_voxels = sim.mask.n_voxels;
net_sign = sim.design.network.sign;
fprintf('  Network: %d positive blob(s), %d negative blob(s).\n\n', ...
        sum(net_sign > 0), sum(net_sign < 0));

%% --- Step 2: build the BOLD regressor -------------------------------------
% A naturalistic analysis begins with a continuous feature of the stimulus -
% audio RMS, optical flow, word surprisal. Convolving it with an HRF turns it
% into a regressor that predicts the BOLD response. Here W.neural supplies the
% example feature time series.
fprintf('Step 2: Building the BOLD regressor...\n');

hrf         = fmri_doublegamma(0:TR:30)';
feature_reg = W.neural(:, 1, 1);

bold_reg = conv(feature_reg, hrf);
bold_reg = bold_reg(1:T);

% Detrend the regressor to match the detrending applied to the data before
% calculating their correlation. The regressor is not residualized against
% the example motion parameters because those parameters are generated
% independently of the simulated task. Z-scoring does not change the
% correlation but places the regressor on a convenient standardized scale.
%
% A 1 x T input could represent one time series or one time point across
% voxels. Here it is one regressor sampled over time, so temporarily suppress
% the toolbox's orientation warning.
warn_state = warning('off', 'fmri:ambiguousOrientation');
bold_reg   = fmri_detrend(bold_reg(:)', 6)';
warning(warn_state);
bold_reg   = (bold_reg - mean(bold_reg)) ./ std(bold_reg);
fprintf('  HRF-convolved, detrended (6 knots), z-scored.\n\n');

figure('Name', 'Step 2: regressor construction');
subplot(2,1,1);
plot(1:T, feature_reg, 'k', 'LineWidth', 1.2);
title('Stimulus feature, as passed to the convolution');
xlabel('Volume'); ylabel('Amplitude'); axis tight;

subplot(2,1,2);
plot(1:T, bold_reg, 'r', 'LineWidth', 1.5);
title('BOLD regressor after HRF convolution, detrending and z-scoring');
xlabel('Volume'); ylabel('Amplitude'); axis tight;

%% --- Step 3: first-level analysis -----------------------------------------
% The simulated data do not contain motion-related artefacts. This step
% therefore demonstrates how fmri_correctmovement reads a standard six-column
% SPM/FSL motion file, not how well it removes known motion contamination.
fprintf('Step 3: First-level analysis...\n');

r_maps = zeros(n_voxels, n_subj);

for p = 1:n_subj
    data_p = fmri_simget(X_comp, svd_info, p, 1);

    motion = zeros(T, 6);               % autocorrelated motion parameters
    for t = 2:T
        motion(t,:) = 0.9 * motion(t-1,:) + 0.05 * randn(1,6);
    end
    motion_file = fullfile(tempdir, sprintf('demo_motion_p%d.txt', p));
    save(motion_file, 'motion', '-ascii');

    data_p      = fmri_detrend(data_p, 6);
    data_p      = fmri_correctmovement(data_p, motion_file);
    data_p      = fmri_zscorevoldata(data_p);
    r_maps(:,p) = fmri_corregressor(bold_reg, data_p);

    delete(motion_file);
    fprintf('  Participant %d/%d: detrend, motion, z-score, correlate\n', p, n_subj);
end
fprintf('\n');

%% --- Step 4: group inference ----------------------------------------------
fprintf('Step 4: Group inference...\n');

% Apply the Fisher transformation before averaging correlations across
% participants, then transform the group mean back to the correlation scale
% for reporting.
z_maps  = atanh(r_maps);
r_group = tanh(mean(z_maps, 2));

% The group test treats participants as observations, so its degrees of
% freedom are n_subj - 1 (not a quantity based on the time points).
[t_map, p_map, df_group] = fmri_ttest(z_maps);
t_crit = fmri_p2t(alpha_th, df_group);

fprintf('  df = %d, |t| >= %.2f at p < %.3f (two-tailed)\n', ...
        df_group, t_crit, alpha_th);
fprintf('  Significant voxels, uncorrected: %d\n\n', sum(p_map < alpha_th));

%% --- Step 5: regions and visualisation ------------------------------------
% The p-map identifies significant voxels but not the direction of the effect.
% Use the sign of the t-map to separate positive and negative results.
%
% The 20-voxel minimum is used only to make the displayed maps easier to read;
% it is not an inferential cluster threshold. See demo_csizeestimation for
% cluster thresholds derived from spatial smoothness.
fprintf('Step 5: Regions and visualisation...\n');

display_CS = 20;

disp_pos = fmri_cleanclusters(p_map < alpha_th & t_map > 0, display_CS, 0);
disp_neg = fmri_cleanclusters(p_map < alpha_th & t_map < 0, display_CS, 0);
disp_map = double(disp_pos | disp_neg);
fprintf('  After the 20-voxel display filter: %d positive, %d negative\n', ...
        sum(disp_pos), sum(disp_neg));

if sum(disp_map) > 0
    fmri_regiontable(disp_map, r_group, 20, 5, 1);
else
    fprintf(['  No voxels survived the %.3f threshold and the 20-voxel ' ...
             'display filter.\n'], alpha_th);
end
fprintf('\n');

% Use separate figures because the toolbox viewers manage figure-level state
% and do not support subplot panels reliably.
figure('Name', 'Group t-map');
t_lim = max(3*t_crit, max(abs(t_map)));
fmri_showslices(t_map, 1, 2, [-t_lim t_lim], [], [], 1, [], t_crit);
title(sprintf('Group t-map (p < %.3f, |t| >= %.2f, df = %d)', ...
      alpha_th, t_crit, df_group));

figure('Name', 'Surviving clusters, signed');
signed_map = double(disp_pos > 0) - double(disp_neg > 0);
fmri_showslices(signed_map, 1, 2, [-1 1], [], [], 1, [], 0.5);
title(sprintf('Red positive, blue negative (%d voxels, 20-voxel display filter)', ...
      sum(disp_map)));

% Show one participant-level map for comparison with the group result. The
% value 0.3 is an illustrative display threshold, not an inferential one.
% demo_xcorr demonstrates thresholds based on effective degrees of freedom.
figure('Name', 'First-level r-map, participant 1');
fmri_showslices(r_maps(:,1), 1, 2, [-0.6 0.6], [], [], 1, [], 0.3);
title('Participant 1, first-level r-map (DISPLAY threshold |r| >= 0.3)');

if sum(disp_map) > 0
    figure('Name', '3D isosurface');
    fmri_show3d(disp_map, 40, 15, 0.5, 0.8, [0.2 0.5 0.9], 0.05);
    title('Stimulus correlates (3D)');
end

fprintf('=== Naturalistic pipeline demo complete ===\n');
fprintf(['The simulation contained %d positive and %d negative network ' ...
    'blob(s).\nThe two-tailed analysis displays the response directions ' ...
    'separately.\nsim.truth.population contains the expected voxel-wise ' ...
    'correlations \nfor optional recovery assessment, if you want to'...
    'score the recovery \nyourself.\n'], ...
    sum(net_sign > 0), sum(net_sign < 0));

